//! Toate textele interfetei, intr-un singur loc, in romana si engleza.
//!
//! **Se strica astfel:** un text nou se scrie direct in `.slint` si ramane
//! pe veci intr-o singura limba — exact ce s-a intamplat pana acum. De-aia
//! `.slint` n-are voie sa contina text pentru om: ia totul din globalul
//! `Texte`, umplut de aici.
//!
//! Lista e una singura (`cu_textele!`). Un camp adaugat in `Texte` si uitat
//! in lista nu compileaza, iar unul pus in lista si uitat in `.slint` cade la
//! `aplica_limba`.

/// Limba interfetei: aceeasi cu cea din `core`, ca textele facute acolo
/// (numele tipurilor, „difera in") sa urmeze acelasi comutator.
pub use gmotion_core::Limba;

/// Tabelul de texte al limbii.
pub fn texte(l: Limba) -> &'static Texte {
    match l {
        Limba::Romana => &RO,
        Limba::Engleza => &EN,
    }
}

